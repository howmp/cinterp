//! Build-time generator for cinterp's external-symbol link indexes.
//!
//! The only inputs are the installed Zig toolchain's own linker metadata:
//!
//!   * Windows: `<zig lib>/libc/mingw/{lib32,lib64,lib-common}/*.def` plus the
//!     `lib-common/*.def.in` templates, preprocessed with
//!     `zig cc -E -P -x c -DDEF_X64|-DDEF_I386 -I <mingw>/def-include`.
//!   * Linux: `<zig lib>/libc/glibc/abilists` (the same binary symbol/version
//!     table Zig uses when linking glibc), restricted to x86_64-linux-gnu and
//!     aarch64-linux-gnu.
//!
//! `build.zig` builds this as a host tool and runs it twice; the outputs are a
//! compact `.bin` blob plus a tiny wrapper module that `@embedFile`s it.
//! Nothing here needs network access, Python or checked-in link metadata.
//!
//! Usage:
//!   gen_link_index win  <zig-exe> <out.bin> <out.zig>
//!   gen_link_index libc <zig-exe> <out.bin> <out.zig>

const std = @import("std");
const link_index = @import("link_index");

const Allocator = std.mem.Allocator;

const Kind = enum { win, libc };

const ZigEnv = struct {
    lib_dir: []const u8,
    version: []const u8,
};

pub fn main() !void {
    var gpa = std.heap.GeneralPurposeAllocator(.{}){};
    defer _ = gpa.deinit();
    var arena_instance = std.heap.ArenaAllocator.init(gpa.allocator());
    defer arena_instance.deinit();
    const allocator = arena_instance.allocator();

    const args = try std.process.argsAlloc(allocator);
    if (args.len != 5) {
        std.debug.print(
            "usage: gen_link_index <win|libc> <zig-exe> <out.bin> <out.zig>\n",
            .{},
        );
        std.process.exit(2);
    }
    const kind = std.meta.stringToEnum(Kind, args[1]) orelse {
        std.debug.print("gen_link_index: unknown index kind '{s}' (expected win or libc)\n", .{args[1]});
        std.process.exit(2);
    };
    const zig_exe = args[2];
    const out_bin = args[3];
    const out_zig = args[4];

    const env = try readZigEnv(allocator, zig_exe);
    const blob = switch (kind) {
        .win => try generateWindows(allocator, env, zig_exe),
        .libc => try generateGlibc(allocator, env),
    };
    const header = try link_index.parse(blob);
    const source_id = header.source(blob);

    try writeOutputs(allocator, out_bin, out_zig, blob, source_id, header.entry_count, header.lib_count);
    std.debug.print(
        "gen_link_index: {s}: {d} entries, {d} libraries, {d} bytes ({s})\n",
        .{ @tagName(kind), header.entry_count, header.lib_count, blob.len, source_id },
    );
}

fn readZigEnv(allocator: Allocator, zig_exe: []const u8) !ZigEnv {
    const result = try std.process.Child.run(.{
        .allocator = allocator,
        .argv = &.{ zig_exe, "env" },
        .max_output_bytes = 16 * 1024 * 1024,
    });
    defer allocator.free(result.stdout);
    defer allocator.free(result.stderr);
    switch (result.term) {
        .Exited => |code| {
            if (code != 0) {
                std.debug.print("gen_link_index: '{s} env' failed with exit code {d}: {s}\n", .{
                    zig_exe, code, result.stderr,
                });
                return error.ZigEnvFailed;
            }
        },
        else => {
            std.debug.print("gen_link_index: '{s} env' terminated abnormally\n", .{zig_exe});
            return error.ZigEnvFailed;
        },
    }
    const parsed = std.json.parseFromSliceLeaky(
        struct { lib_dir: []const u8, version: []const u8 },
        allocator,
        result.stdout,
        .{ .ignore_unknown_fields = true },
    ) catch |err| {
        std.debug.print("gen_link_index: could not parse '{s} env' output: {s}\n", .{ zig_exe, @errorName(err) });
        return error.ZigEnvFailed;
    };
    if (parsed.lib_dir.len == 0) {
        std.debug.print("gen_link_index: '{s} env' reported an empty lib_dir\n", .{zig_exe});
        return error.ZigEnvFailed;
    }
    // `parseFromSliceLeaky` may point into `result.stdout`; copy before the
    // temporary buffers are released.
    return .{
        .lib_dir = try allocator.dupe(u8, parsed.lib_dir),
        .version = try allocator.dupe(u8, parsed.version),
    };
}

fn writeOutputs(
    allocator: Allocator,
    out_bin: []const u8,
    out_zig: []const u8,
    blob: []const u8,
    source_id: []const u8,
    entry_count: u32,
    lib_count: u16,
) !void {
    try std.fs.cwd().writeFile(.{ .sub_path = out_bin, .data = blob });

    const out_dir = std.fs.path.dirname(out_zig) orelse ".";
    const relative = try std.fs.path.relative(allocator, out_dir, out_bin);
    const embed_path = try allocator.dupe(u8, relative);
    for (embed_path) |*byte| {
        if (byte.* == '\\') byte.* = '/';
    }
    const wrapper = try std.fmt.allocPrint(
        allocator,
        "// Generated by compiler/tools/gen_link_index.zig. Do not edit.\n" ++
            "pub const source_id: []const u8 = \"{s}\";\n" ++
            "pub const entry_count: u32 = {d};\n" ++
            "pub const lib_count: u16 = {d};\n" ++
            "pub const blob: []const u8 align(8) = @embedFile(\"{s}\");\n",
        .{ source_id, entry_count, lib_count, embed_path },
    );
    try std.fs.cwd().writeFile(.{ .sub_path = out_zig, .data = wrapper });
}

// ---------------------------------------------------------------------------
// Windows: MinGW .def files
// ---------------------------------------------------------------------------

const DefArch = enum(u8) {
    x86_64 = 1,
    x86 = 2,
    common = 3,
};

fn maskFor(arch: DefArch) u8 {
    return switch (arch) {
        .x86_64 => 1,
        .x86 => 2,
        .common => 3,
    };
}

fn generateWindows(allocator: Allocator, env: ZigEnv, zig_exe: []const u8) ![]u8 {
    const mingw = try std.fs.path.join(allocator, &.{ env.lib_dir, "libc", "mingw" });
    var probe = std.fs.cwd().openDir(mingw, .{}) catch {
        std.debug.print(
            "gen_link_index: Zig MinGW link metadata not found at {s}\n" ++
                "  cinterp needs a complete Zig 0.13 toolchain (libc/mingw); set ZIG_LIB_DIR if Zig is installed elsewhere.\n",
            .{mingw},
        );
        return error.MissingMinGWDefs;
    };
    probe.close();

    const def_include = try std.fs.path.join(allocator, &.{ mingw, "def-include" });
    var include_probe = std.fs.cwd().openDir(def_include, .{}) catch {
        std.debug.print(
            "gen_link_index: Zig MinGW def-include not found at {s}\n" ++
                "  cinterp needs the complete libc/mingw tree from Zig 0.13.\n",
            .{def_include},
        );
        return error.MissingMinGWDefs;
    };
    include_probe.close();

    const source_id = try std.fmt.allocPrint(allocator, "mingw-defs@{s}", .{env.version});
    var builder = link_index.Builder.init(allocator, .windows, source_id);
    defer builder.deinit();

    // Architecture-specific gendef output has x86 stdcall decoration
    // (`MessageBoxA@16`); it is the most authoritative spelling.
    for ([_]struct { dir: []const u8, arch: DefArch }{
        .{ .dir = "lib64", .arch = .x86_64 },
        .{ .dir = "lib32", .arch = .x86 },
    }) |item| {
        const path = try std.fs.path.join(allocator, &.{ mingw, item.dir });
        var files = std.ArrayList([]const u8).init(allocator);
        defer files.deinit();
        try collectFiles(allocator, path, ".def", &files);
        if (files.items.len == 0) {
            std.debug.print(
                "gen_link_index: no MinGW .def files under {s}\n" ++
                    "  cinterp needs the complete libc/mingw tree from Zig 0.13.\n",
                .{path},
            );
            return error.MissingMinGWDefs;
        }
        for (files.items) |file| {
            const text = std.fs.cwd().readFileAlloc(allocator, file, 32 * 1024 * 1024) catch |err| {
                std.debug.print("gen_link_index: cannot read {s}: {s}\n", .{ file, @errorName(err) });
                return err;
            };
            try addDefText(allocator, &builder, text, item.arch, 0, false);
        }
    }

    // Common pre-generated defs apply to both supported Windows architectures.
    {
        const path = try std.fs.path.join(allocator, &.{ mingw, "lib-common" });
        var files = std.ArrayList([]const u8).init(allocator);
        defer files.deinit();
        try collectFiles(allocator, path, ".def", &files);
        for (files.items) |file| {
            const text = std.fs.cwd().readFileAlloc(allocator, file, 32 * 1024 * 1024) catch |err| {
                std.debug.print("gen_link_index: cannot read {s}: {s}\n", .{ file, @errorName(err) });
                return err;
            };
            try addDefText(allocator, &builder, text, .common, 1, isWindowsAppFile(file));
        }

        // Templates (`kernel32.def.in`, `user32.def.in`, ...) are in C
        // preprocessor syntax. Zig ships clang, so reuse `zig cc -E` instead
        // of reimplementing the macro subset.
        var templates = std.ArrayList([]const u8).init(allocator);
        defer templates.deinit();
        try collectFiles(allocator, path, ".def.in", &templates);
        for (templates.items) |file| {
            inline for ([_]DefArch{ .x86_64, .x86 }) |arch| {
                const text = try preprocessDef(allocator, zig_exe, def_include, file, arch);
                try addDefText(allocator, &builder, text, arch, 1, isWindowsAppFile(file));
            }
        }
    }

    return builder.finish();
}

fn collectFiles(
    allocator: Allocator,
    path: []const u8,
    suffix: []const u8,
    out: *std.ArrayList([]const u8),
) !void {
    var dir = std.fs.cwd().openDir(path, .{ .iterate = true }) catch |err| {
        std.debug.print("gen_link_index: cannot open {s}: {s}\n", .{ path, @errorName(err) });
        return err;
    };
    defer dir.close();
    var iterator = dir.iterate();
    while (try iterator.next()) |entry| {
        if (entry.kind != .file and entry.kind != .sym_link) continue;
        if (!std.mem.endsWith(u8, entry.name, suffix)) continue;
        try out.append(try std.fs.path.join(allocator, &.{ path, entry.name }));
    }
    std.mem.sort([]const u8, out.items, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.order(u8, a, b) == .lt;
        }
    }.lessThan);
}

fn isWindowsAppFile(path: []const u8) bool {
    return std.mem.endsWith(u8, path, "_windowsapp.def") or
        std.mem.endsWith(u8, path, "_windowsapp.def.in");
}

fn preprocessDef(
    allocator: Allocator,
    zig_exe: []const u8,
    def_include: []const u8,
    path: []const u8,
    arch: DefArch,
) ![]u8 {
    const define = if (arch == .x86_64) "-DDEF_X64" else "-DDEF_I386";
    const result = try std.process.Child.run(.{
        .allocator = allocator,
        .argv = &.{ zig_exe, "cc", "-E", "-P", "-x", "c", "-w", define, "-I", def_include, path },
        .max_output_bytes = 64 * 1024 * 1024,
    });
    defer allocator.free(result.stderr);
    switch (result.term) {
        .Exited => |code| {
            if (code != 0) {
                std.debug.print(
                    "gen_link_index: preprocessing {s} with {s} failed (exit {d}):\n{s}\n",
                    .{ path, define, code, result.stderr },
                );
                allocator.free(result.stdout);
                return error.MingwPreprocessFailed;
            }
        },
        else => {
            allocator.free(result.stdout);
            std.debug.print("gen_link_index: preprocessing {s} terminated abnormally\n", .{path});
            return error.MingwPreprocessFailed;
        },
    }
    return result.stdout;
}

const DefParser = struct {
    allocator: Allocator,
    builder: *link_index.Builder,
    arch: DefArch,
    rank: u8,
    windowsapp: bool,
    dll: ?[]const u8 = null,

    fn run(self: *DefParser, text: []const u8) !void {
        var lines = std.mem.splitScalar(u8, text, '\n');
        while (lines.next()) |raw| {
            var line = std.mem.trim(u8, raw, " \t\r");
            if (line.len == 0) continue;
            if (line[0] == ';' or line[0] == '#') continue;
            if (try self.libraryLine(line)) |name| {
                self.dll = name;
                continue;
            }
            if (isDirectiveLine(line)) continue;
            const dll = self.dll orelse continue;
            if (std.mem.indexOfScalar(u8, line, ';')) |index| {
                line = std.mem.trim(u8, line[0..index], " \t");
                if (line.len == 0) continue;
            }
            try self.symbolLine(dll, line);
        }
    }

    fn libraryLine(self: *DefParser, line: []const u8) !?[]const u8 {
        if (!std.ascii.startsWithIgnoreCase(line, "LIBRARY")) return null;
        if (line.len > "LIBRARY".len) {
            const next = line["LIBRARY".len];
            if (!std.ascii.isWhitespace(next) and next != '"') return null;
        }
        var rest = std.mem.trim(u8, line["LIBRARY".len..], " \t");
        if (rest.len == 0) return null;
        var name: []const u8 = undefined;
        if (rest[0] == '"') {
            const end = std.mem.indexOfScalarPos(u8, rest, 1, '"') orelse rest.len;
            name = rest[1..end];
        } else {
            const end = std.mem.indexOfAny(u8, rest, " \t") orelse rest.len;
            name = rest[0..end];
        }
        if (name.len == 0) return null;
        return try std.ascii.allocLowerString(self.allocator, name);
    }

    fn symbolLine(self: *DefParser, dll: []const u8, line: []const u8) !void {
        // PE executables (ntoskrnl.exe, ...) are not user-mode LoadLibrary
        // providers and must never win a provider lookup.
        if (std.mem.endsWith(u8, dll, ".exe")) return;
        var name_token: []const u8 = undefined;
        var target_token: []const u8 = undefined;
        var aliased = false;

        if (std.mem.indexOf(u8, line, "==")) |position| {
            const left = std.mem.trim(u8, line[0..position], " \t");
            const right = std.mem.trim(u8, line[position + 2 ..], " \t");
            name_token = firstToken(left);
            target_token = firstToken(right);
            aliased = true;
        } else if (singleEquals(line)) |position| {
            const left = std.mem.trim(u8, line[0..position], " \t");
            const right = std.mem.trim(u8, line[position + 1 ..], " \t");
            name_token = firstToken(left);
            target_token = firstToken(right);
            aliased = true;
        } else {
            name_token = firstToken(line);
            target_token = name_token;
        }
        if (name_token.len == 0 or target_token.len == 0) return;
        if (name_token[0] == '@' or target_token[0] == '@') return;

        var flags: u8 = 0;
        var tokens = std.mem.tokenizeAny(u8, line, " \t");
        while (tokens.next()) |token| {
            if (std.ascii.eqlIgnoreCase(token, "NONAME")) return; // ordinal-only export
            if (std.ascii.eqlIgnoreCase(token, "DATA")) flags |= 1;
            if (token.len > 1 and token[0] == '@') return; // `name @12` ordinal form
        }

        const name_info = cleanExportName(name_token) orelse return;
        const target_info = cleanExportName(target_token) orelse return;

        const decorated = name_info.decorated or target_info.decorated;
        var conv_bits: u8 = 0;
        if (self.arch == .x86 or self.arch == .common) {
            if (decorated) conv_bits |= 1;
        }
        if (self.arch == .x86_64 or self.arch == .common) {
            if (!isCrtDll(dll)) conv_bits |= 2;
        }
        const symbol_rank: u8 = self.rank * 2 + @as(u8, if (decorated) 0 else 1);
        const priority = libPriority(dll, self.rank == 0, self.windowsapp);
        const arch_mask = maskFor(self.arch);

        try self.builder.add(.{
            .key = name_info.base,
            .symbol = target_info.base,
            .lib = dll,
            .arch_mask = arch_mask,
            .conv_bits = conv_bits,
            .priority = priority,
            .flags = flags,
            .rank = symbol_rank,
        });
        if (aliased and !std.mem.eql(u8, name_info.base, target_info.base)) {
            // `close == _close`: code may reference either spelling, both
            // resolve to the actual DLL export `_close`.
            try self.builder.add(.{
                .key = target_info.base,
                .symbol = target_info.base,
                .lib = dll,
                .arch_mask = arch_mask,
                .conv_bits = conv_bits,
                .priority = priority,
                .flags = flags,
                .rank = symbol_rank,
            });
        }
    }
};

fn firstToken(line: []const u8) []const u8 {
    const trimmed = std.mem.trim(u8, line, " \t");
    if (trimmed.len == 0) return trimmed;
    const end = std.mem.indexOfAny(u8, trimmed, " \t") orelse trimmed.len;
    return trimmed[0..end];
}

fn singleEquals(line: []const u8) ?usize {
    const position = std.mem.indexOfScalar(u8, line, '=') orelse return null;
    if (position + 1 < line.len and line[position + 1] == '=') return null;
    return position;
}

fn isDirectiveLine(line: []const u8) bool {
    const token = firstToken(line);
    const directives = [_][]const u8{
        "EXPORTS", "DESCRIPTION", "STACKSIZE", "SECTIONS", "VERSION",
        "NAME",    "HEAPSIZE",    "IMPORTS",   "CODE",     "SEGMENTS",
    };
    for (directives) |directive| {
        if (std.ascii.eqlIgnoreCase(token, directive)) return true;
    }
    return false;
}

const ExportName = struct {
    base: []const u8,
    decorated: bool,
};

/// Strip x86 stdcall decoration (`Name@12` or `_Name@12`) and reject names
/// that a C plan cannot reference (C++ mangling, ordinal placeholders, ...).
fn cleanExportName(raw: []const u8) ?ExportName {
    var name = std.mem.trim(u8, raw, " \t");
    if (name.len == 0) return null;
    var decorated = false;
    if (std.mem.lastIndexOfScalar(u8, name, '@')) |position| {
        if (position > 0 and isAllDigits(name[position + 1 ..])) {
            name = name[0..position];
            decorated = true;
        }
    }
    if (!isCIdentifier(name)) return null;
    return .{ .base = name, .decorated = decorated };
}

fn isCIdentifier(name: []const u8) bool {
    if (name.len == 0) return false;
    if (!std.ascii.isAlphabetic(name[0]) and name[0] != '_') return false;
    for (name[1..]) |char| {
        if (!std.ascii.isAlphanumeric(char) and char != '_') return false;
    }
    return true;
}

fn isAllDigits(text: []const u8) bool {
    if (text.len == 0) return false;
    for (text) |char| {
        if (!std.ascii.isDigit(char)) return false;
    }
    return true;
}

fn isCrtDll(dll: []const u8) bool {
    return std.mem.startsWith(u8, dll, "ucrtbase") or
        std.mem.startsWith(u8, dll, "msvcrt") or
        std.mem.startsWith(u8, dll, "ntdll") or
        std.mem.startsWith(u8, dll, "api-ms-win-crt") or
        std.mem.indexOf(u8, dll, "ntdllcrt") != null;
}

fn crtRank(dll: []const u8) u8 {
    if (std.mem.eql(u8, dll, "ucrtbase.dll")) return 0;
    if (std.mem.startsWith(u8, dll, "ucrtbase")) return 1;
    if (std.mem.startsWith(u8, dll, "api-ms-win-crt")) return 2;
    if (std.mem.eql(u8, dll, "msvcrt.dll")) return 3;
    if (std.mem.startsWith(u8, dll, "msvcrt")) return 4;
    if (std.mem.indexOf(u8, dll, "ntdll") != null) return 5;
    return 6;
}

fn libPriority(dll: []const u8, arch_specific: bool, windowsapp: bool) u8 {
    var priority: u8 = if (arch_specific) 0 else 2;
    if (windowsapp) priority += 4;
    if (std.mem.startsWith(u8, dll, "api-ms-win-")) priority += 16;
    priority += crtRank(dll);
    return priority;
}

fn addDefText(
    allocator: Allocator,
    builder: *link_index.Builder,
    text: []const u8,
    arch: DefArch,
    rank: u8,
    windowsapp: bool,
) !void {
    var parser = DefParser{
        .allocator = allocator,
        .builder = builder,
        .arch = arch,
        .rank = rank,
        .windowsapp = windowsapp,
    };
    try parser.run(text);
}

