const supported_targets = [_]struct { name: []const u8, arch: u8, mask: u8 }{
    .{ .name = "x86_64-linux-gnu", .arch = link_index.arch_x86_64, .mask = 1 },
    .{ .name = "aarch64-linux-gnu", .arch = link_index.arch_aarch64, .mask = 4 },
};

fn glibcLibrary(lib: []const u8) ?struct { soname: []const u8, priority: u8 } {
    if (std.mem.eql(u8, lib, "c")) return .{ .soname = "libc.so.6", .priority = 0 };
    if (std.mem.eql(u8, lib, "m")) return .{ .soname = "libm.so.6", .priority = 1 };
    if (std.mem.eql(u8, lib, "pthread")) return .{ .soname = "libpthread.so.0", .priority = 2 };
    if (std.mem.eql(u8, lib, "dl")) return .{ .soname = "libdl.so.2", .priority = 3 };
    if (std.mem.eql(u8, lib, "rt")) return .{ .soname = "librt.so.1", .priority = 4 };
    if (std.mem.eql(u8, lib, "util")) return .{ .soname = "libutil.so.1", .priority = 5 };
    if (std.mem.eql(u8, lib, "resolv")) return .{ .soname = "libresolv.so.2", .priority = 6 };
    // `ld` (ld-linux) is the dynamic loader; it must never be a default
    // dlopen provider.
    return null;
}

fn generateGlibc(allocator: Allocator, env: ZigEnv) ![]u8 {
    const path = try std.fs.path.join(allocator, &.{ env.lib_dir, "libc", "glibc", "abilists" });
    const data = std.fs.cwd().readFileAlloc(allocator, path, 64 * 1024 * 1024) catch |err| {
        std.debug.print(
            "gen_link_index: Zig glibc abilists not found at {s} ({s})\n" ++
                "  cinterp needs a complete Zig 0.13 toolchain (libc/glibc/abilists); set ZIG_LIB_DIR if Zig is installed elsewhere.\n",
            .{ path, @errorName(err) },
        );
        return error.MissingGlibcAbilists;
    };

    const source_id = try std.fmt.allocPrint(allocator, "glibc-abilists@{s}", .{env.version});
    var builder = link_index.Builder.init(allocator, .glibc, source_id);
    defer builder.deinit();

    var stream = std.io.fixedBufferStream(data);
    const reader = stream.reader();

    var libs = std.ArrayList([]const u8).init(allocator);
    const lib_count = reader.readByte() catch |err| return invalidAbilists(err);
    var li: usize = 0;
    while (li < lib_count) : (li += 1) {
        libs.append(try reader.readUntilDelimiterAlloc(allocator, 0, 128)) catch |err| return invalidAbilists(err);
    }

    const version_count = reader.readByte() catch |err| return invalidAbilists(err);
    var vi: usize = 0;
    while (vi < version_count) : (vi += 1) {
        _ = reader.readByte() catch |err| return invalidAbilists(err);
        _ = reader.readByte() catch |err| return invalidAbilists(err);
        _ = reader.readByte() catch |err| return invalidAbilists(err);
    }

    var target_names = std.ArrayList([]const u8).init(allocator);
    const target_count = reader.readByte() catch |err| return invalidAbilists(err);
    var ti: usize = 0;
    while (ti < target_count) : (ti += 1) {
        target_names.append(try reader.readUntilDelimiterAlloc(allocator, 0, 128)) catch |err| return invalidAbilists(err);
    }

    var supported = std.ArrayList(struct { bit: u5, mask: u8 }).init(allocator);
    for (target_names.items, 0..) |name, index| {
        for (supported_targets) |target| {
            if (!std.mem.eql(u8, name, target.name)) continue;
            try supported.append(.{ .bit = @intCast(index), .mask = target.mask });
        }
    }
    if (supported.items.len == 0) {
        std.debug.print("gen_link_index: {s} has no x86_64-linux-gnu/aarch64-linux-gnu targets\n", .{path});
        return error.MissingGlibcAbilists;
    }

    const function_count = reader.readInt(u16, .little) catch |err| return invalidAbilists(err);
    var current: ?[]const u8 = null;
    var function_index: usize = 0;
    while (function_index < function_count) : (function_index += 1) {
        const symbol = current orelse blk: {
            const name = reader.readUntilDelimiterAlloc(allocator, 0, 256) catch |err| return invalidAbilists(err);
            current = name;
            break :blk name;
        };
        const target_mask_raw = reader.readInt(u32, .little) catch |err| return invalidAbilists(err);
        const lib_index = reader.readByte() catch |err| return invalidAbilists(err);
        const terminal = (target_mask_raw & (@as(u32, 1) << 31)) != 0;
        const target_mask = target_mask_raw & ~(@as(u32, 1) << 31);
        while (true) {
            const byte = reader.readByte() catch |err| return invalidAbilists(err);
            if ((byte & 0x80) != 0) break;
        }
        if (terminal) current = null;

        const index = lib_index & 0x1f;
        if (index >= libs.items.len) continue;
        const mapped = glibcLibrary(libs.items[index]) orelse continue;
        var arch_mask: u8 = 0;
        for (supported.items) |target| {
            if ((target_mask & (@as(u32, 1) << target.bit)) != 0) arch_mask |= target.mask;
        }
        if (arch_mask == 0) continue;
        try builder.add(.{
            .key = symbol,
            .symbol = symbol,
            .lib = mapped.soname,
            .arch_mask = arch_mask,
            .conv_bits = 0,
            .priority = mapped.priority,
            .rank = 0,
        });
    }

    return builder.finish();
}

fn invalidAbilists(err: anyerror) anyerror {
    std.debug.print("gen_link_index: malformed Zig glibc abilists: {s}\n", .{@errorName(err)});
    return error.MalformedGlibcAbilists;
}
